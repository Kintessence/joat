function apagar_vocabulos() {
    // Obtém todas as postagens do tipo 'vocabulo'
    $vocabulos = get_posts(array(
        'post_type' => 'vocabulo',
        'numberposts' => -1, // -1 para obter todas as postagens
    ));

    // Exclui cada postagem
    foreach ($vocabulos as $vocabulo) {
        wp_delete_post($vocabulo->ID, true); // O segundo parâmetro true exclui permanentemente
    }
}

